CREATE TABLE lyfter_car_rental.Automoviles (
    automovil_id     SERIAL PRIMARY KEY,
    marca            VARCHAR(50) NOT NULL,
    modelo           VARCHAR(50) NOT NULL,
    anio_fabricacion INT NOT NULL CHECK (anio_fabricacion BETWEEN 1950 AND 2100),
    estado           VARCHAR(20) NOT NULL DEFAULT 'Disponible'
    CHECK (estado IN ('Disponible', 'Alquilado', 'Mantenimiento', 'Deshabilitado'))
);

